export type TranslationKey = keyof typeof EN;

const DICT: Record<Lang, typeof EN> = { en: EN, ur: UR, roman: ROMAN };

interface I18nContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: TranslationKey) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<Lang>(() => {
    if (typeof window === 'undefined') return 'en';
    const stored = window.localStorage.getItem('tp-lang');
    if (stored === 'ur' || stored === 'roman' || stored === 'en') return stored;
    return 'en';
  });

  useEffect(() => {
    document.documentElement.lang = lang === 'ur' ? 'ur' : 'en';
    document.documentElement.dir = lang === 'ur' ? 'rtl' : 'ltr';
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    window.localStorage.setItem('tp-lang', next);
  }, []);

  const t = useCallback((key: TranslationKey) => DICT[lang][key] ?? EN[key], [lang]);

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return React.createElement(I18nContext.Provider, { value }, children);
};

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
